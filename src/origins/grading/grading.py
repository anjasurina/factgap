def organize_experiment_data_by_iteration(
    filepath: Optional[str] = None,
    experiment_results: Optional[ExperimentResult] = None,
    return_experiment_results: bool = False
) -> dict[int, list[PromptParsedResults]] | tuple[dict[int, list[PromptParsedResults]], ExperimentResult]:
    """
    Organize the experiment data by iteration.

    Args:
        filepath (str): The path to the JSON file containing the experiment data.
        experiment_results (ExperimentResult): An object containing the loaded experiment data.
        return_experiment_results (bool): If True, return the experiment results.

    Returns:
        dict[int, list[PromptParsedResults]]: A dictionary where the keys are iteration numbers and the values are PromptParsedResults objects.
        Each PromptParsedResults object contains the prompt and the parsed responses for that iteration.
        If return_experiment_results is True, also return the experiment results.

    Raises:
        ValueError: If neither filepath nor experiment_results is provided.
    """

    if not filepath and not experiment_results:
        raise ValueError(
            "Either filepath or experiment_results must be provided")

    if filepath:
        experiment_results = load_experiment_data(filepath)

    if experiment_results is None:
        raise ValueError(
            "ExperimentResult is None. Please provide a valid filepath or experiment_results.")

    results_by_iteration = defaultdict(list)
    for prompt_results in experiment_results.results:
        prompt = prompt_results.prompt

        for response_output in prompt_results.response_outputs:
            iteration = response_output.iteration

            results_by_iteration[iteration].append(
                PromptParsedResults(prompt=prompt,
                                    parsed_responses=response_output.parsed_responses,
                                    api_verdicts=response_output.api_verdicts,
                                    responses=response_output.responses,
                                    char_lengths=response_output.char_lengths
                                    )
            )

    if return_experiment_results:
        return results_by_iteration, experiment_results
    else:
        return results_by_iteration
